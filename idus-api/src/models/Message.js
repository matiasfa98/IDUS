// src/models/Message.js
import mongoose from "mongoose";

const ATTACHMENT_KINDS = ["image", "file", "audio"]; // video deferred

const attachmentSchema = new mongoose.Schema(
  {
    kind: { type: String, enum: ATTACHMENT_KINDS, required: true },
    url: { type: String, required: true },
    thumbUrl: { type: String, default: null },
    mimeType: { type: String, required: true },
    size: { type: Number, required: true }, // bytes
    width: { type: Number, default: null },
    height: { type: Number, default: null },
    duration: { type: Number, default: null }, // seconds, audio only
    originalName: { type: String, default: null },
    cloudinaryPublicId: { type: String, default: null },
  },
  { _id: false }
);

const messageSchema = new mongoose.Schema(
  {
    conversationId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Conversation",
      required: true,
      index: true,
    },
    senderId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    // ULID — sortable by creation time, generated by the client.
    // Also used for idempotency: unique per sender.
    clientMessageId: { type: String, required: true },

    body: { type: String, default: "" },
    attachments: { type: [attachmentSchema], default: [] },

    replyToId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Message",
      default: null,
    },

    reactions: { type: mongoose.Schema.Types.Mixed, default: {} },

    editedAt: { type: Date, default: null },
    deletedAt: { type: Date, default: null },

    // Client's clock, for offline ordering. Server's createdAt is authoritative.
    localTimestamp: { type: Date, required: true },
  },
  { timestamps: true }
);

// Idempotency: same sender cannot insert the same clientMessageId twice.
messageSchema.index(
  { senderId: 1, clientMessageId: 1 },
  { unique: true }
);

// History pagination — newest first per conversation.
messageSchema.index({ conversationId: 1, createdAt: -1 });

// Reply lookup (rare).
messageSchema.index({ replyToId: 1 }, { sparse: true });

export const Message = mongoose.model("Message", messageSchema);
export const ATTACHMENT_KINDS_ENUM = ATTACHMENT_KINDS;